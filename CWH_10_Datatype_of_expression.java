public class CWH_10_Datatype_of_expression {
    public static void main(String[] args) {
        // Data type of expression and increment/decrement operator
        int i = 5;
        System.out.println(i++);
        System.out.println(++i);
        System.out.println(i--);
        System.out.println(--i);

        char a = 'A';
        System.out.println(++a);
    }
}
